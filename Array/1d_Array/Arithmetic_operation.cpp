#include <bits/stdc++.h>
using namespace std;

class solution
{
public:
    int add(int a, int b)
    {
        int sum;
        sum = a + b;
        return sum;
    }

    int subtract(int a, int b)
    {
        int result;
        result = a - b;
        return result;
    }

    int multiply(int a, int b)
    {
        int product;
        product = a * b;
        return product;
    }

    int divide(int a, int b)
    {
        int division;
        division = a / b;
        return division;
    }
};